import type { AiService, ProviderInfo, StreamEvent } from "./types";

export const MOCK_PROVIDER: ProviderInfo = {
  id: "mock",
  name: "Local Preview",
  description: "Built-in mock model that streams sample replies without network access.",
  model: "mock-1",
  isLocal: true,
  status: "ready",
};

export interface MockAiOptions {
  /** Delay between streamed chunks; 0 streams synchronously-fast for tests. */
  tokenDelayMs?: number;
  reply?: (prompt: string) => string;
}

function defaultReply(prompt: string): string {
  const topic = prompt.trim().split(/\s+/).slice(0, 12).join(" ");
  return (
    `You asked about **${topic}**.\n\nHere's a structured starting point:\n\n` +
    "1. **Clarify the goal** — define what success looks like.\n" +
    "2. **Map the constraints** — time, budget, and people.\n" +
    "3. **Pick the smallest next step** — something you can finish today.\n\n" +
    "> This reply was generated by the browser preview mock."
  );
}

function chunk(text: string): string[] {
  return text.match(/\S+\s*|\s+/g) ?? [];
}

/**
 * Webview-side mock used in unit tests and browser previews. The desktop app
 * uses the Rust `MockProvider` through `tauriAi` instead.
 */
export function createMockAi(options: MockAiOptions = {}): AiService {
  const delay = options.tokenDelayMs ?? 18;
  const reply = options.reply ?? defaultReply;

  return {
    listProviders: async () => [MOCK_PROVIDER],

    streamChat(request, onEvent) {
      let cancelled = false;
      const prompt = [...request.messages].reverse().find((m) => m.role === "user")?.content ?? "";
      const emit = (event: StreamEvent) => onEvent(event);
      const wait = () => new Promise<void>((r) => setTimeout(r, delay));

      const done = (async () => {
        await Promise.resolve();
        emit({ type: "started", providerId: MOCK_PROVIDER.id, model: MOCK_PROVIDER.model });
        const pieces = chunk(reply(prompt));
        for (const [index, text] of pieces.entries()) {
          if (cancelled) {
            emit({ type: "completed", finishReason: "cancelled" });
            return;
          }
          if (prompt.includes("/error") && index === Math.min(8, pieces.length - 1)) {
            emit({ type: "error", message: "AI provider error: simulated failure requested with /error" });
            return;
          }
          emit({ type: "delta", text });
          await wait();
        }
        emit({ type: "completed", finishReason: cancelled ? "cancelled" : "stop" });
      })();

      return {
        done,
        cancel: async () => {
          cancelled = true;
        },
      };
    },
  };
}
